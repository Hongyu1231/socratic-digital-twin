"""Write a plain-text extract of a clinician's tutor script (.docx) for the repo.

The tutor script docx stays out of the repo. Its text is committed as an extract
so the content-fidelity test in test_case_content.py runs everywhere. The
extract starts with a header that names the docx and records its SHA-256,
followed by every body paragraph and table cell in document order, one per line
(a table cell's own paragraphs are joined with newlines; a merged cell is
written once).

    python3 scripts/script_text.py \\
        --docx "<private folder>/Molars_Case_1_tutor_script (9Nov26).docx" \\
        --output content/second-molars/case-1.script-9nov.txt

Pass --check instead of writing to confirm an existing extract matches the docx.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

from docx import Document
from docx.table import Table
from docx.text.paragraph import Paragraph

HEADER_SOURCE = "# Source: "
HEADER_SHA256 = "# Source SHA-256: "
HEADER_NOTE = "# Plain-text extract generated by scripts/script_text.py: paragraphs and table cells in document order."


def docx_lines(document) -> list[str]:
    lines: list[str] = []
    body = document.element.body
    for child in body.iterchildren():
        tag = child.tag.rsplit("}", 1)[-1]
        if tag == "p":
            lines.append(Paragraph(child, document).text)
        elif tag == "tbl":
            for row in Table(child, document).rows:
                seen = set()
                for cell in row.cells:
                    if id(cell._tc) in seen:
                        continue
                    seen.add(id(cell._tc))
                    lines.append(cell.text)
    return lines


def extract(docx_path: Path) -> str:
    """Return the extract text, header included, for the given docx."""

    data = Path(docx_path).read_bytes()
    from io import BytesIO

    lines = docx_lines(Document(BytesIO(data)))
    header = [HEADER_SOURCE + Path(docx_path).name, HEADER_SHA256 + hashlib.sha256(data).hexdigest(), HEADER_NOTE, ""]
    return "\n".join(header + lines) + "\n"


def read_extract(path: Path) -> tuple[str, str, str]:
    """Return (source name, source SHA-256, body text) from a committed extract."""

    text = Path(path).read_text(encoding="utf-8")
    source, sha256, note, blank, body = text.split("\n", 4)
    if not source.startswith(HEADER_SOURCE) or not sha256.startswith(HEADER_SHA256) or note != HEADER_NOTE or blank:
        raise ValueError(f"{path} does not start with the script_text.py header")
    return source[len(HEADER_SOURCE):], sha256[len(HEADER_SHA256):], body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--docx", type=Path, required=True, help="The private tutor script .docx")
    parser.add_argument("--output", type=Path, required=True, help="The extract .txt to write (or check)")
    parser.add_argument("--check", action="store_true", help="Only confirm the existing extract matches the docx")
    args = parser.parse_args()
    text = extract(args.docx)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != text:
            print(f"{args.output} does not match {args.docx}", file=sys.stderr)
            return 1
        print(f"{args.output} matches {args.docx}")
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
